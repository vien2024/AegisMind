import pg, { type Pool, type PoolClient, type QueryResult } from "pg";

// ---------------------------------------------------------------------------
// Postgres-backed storage for AegisMind.
//
// Wiring:
//   - DATABASE_URL must be set (production and local development).
//   - When absent the module still loads, but any DB access fails fast with
//     a clear message so missing wiring is obvious.
//
// The old SQLite file path (AEGISMIND_DB / SCOPEWEAVER_DB) is no longer used
// to open a connection. It is kept only as a migration hint for anyone
// carrying existing SQLite data over to Postgres.
// ---------------------------------------------------------------------------

const DATABASE_URL = process.env.DATABASE_URL;

function getPool(): Pool {
  if (!DATABASE_URL) {
    throw new Error(
      "DATABASE_URL is not set. Point this app at a Postgres database, e.g.:\n" +
        "  DATABASE_URL=postgresql://user:password@localhost:5432/aegismind",
    );
  }
  return pool;
}

const pool = new pg.Pool({
  connectionString: DATABASE_URL,
  max: 10,
  idleTimeoutMillis: 30_000,
  connectionTimeoutMillis: 5_000,
});

pool.on("error", (err: Error) => {
  console.error("Postgres pool error:", err);
});

