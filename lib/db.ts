// ---------------------------------------------------------------------------
// Public API surface (kept close to the old better-sqlite3 shape so consumers
// need only small changes).
// ---------------------------------------------------------------------------

export interface DbHandle {
  prepare(sql: string): PreparedQuery;
  transaction<T>(fn: (client: TransactionClient) => T | Promise<T>): Promise<T>;
  query(sql: string, params?: unknown[]): Promise<QueryResult>;
}

/** The application database handle. Use `db().prepare(...).run/.get/.all(...)` */
export function db(): DbHandle {
  return {
    prepare: (sql: string) => prepare(sql, getPool()),
    transaction: <T>(fn: (client: TransactionClient) => T | Promise<T>) =>
      transaction(fn),
    query: (sql: string, params?: unknown[]) => getPool().query(sql, params),
  };
}

export type Database = Pool;

/** Eagerly verify the database is reachable (used by the health endpoint). */
export async function ping(): Promise<void> {
  await getPool().query("SELECT 1");
}

/** ISO-8601 timestamp used consistently across the app. */
export function now(): string {
  return new Date().toISOString();
}

// ---------------------------------------------------------------------------
// Query helpers that mirror the old better-sqlite3 prepared-statement API.
// ---------------------------------------------------------------------------

export interface RunResult {
  lastInsertRowid: number;
  rowsAffected: number;
}

export interface PreparedQuery {
  run(...params: unknown[]): Promise<RunResult>;
  get(...params: unknown[]): Promise<Record<string, unknown> | null>;
  all(...params: unknown[]): Promise<Record<string, unknown>[]>;
  values(...params: unknown[]): Promise<unknown[][]>;
}

export function prepare(sql: string, poolInstance: Pool | PoolClient): PreparedQuery {
  return {
    run: async (...params: unknown[]) => {
      const result = await poolInstance.query(sql, params);
      return {
        lastInsertRowid: normalizeId(result),
        rowsAffected: result.rowCount ?? 0,
      };
    },
    get: async (...params: unknown[]) => {
      const result = await poolInstance.query(sql, params);
      return (result.rows[0] ?? null) as Record<string, unknown> | null;
    },
    all: async (...params: unknown[]) => {
      const result = await poolInstance.query(sql, params);
      return result.rows as Record<string, unknown>[];
    },
    values: async (...params: unknown[]) => {
      const result = await poolInstance.query(sql, params);
      return result.rows as unknown[][];
    },
  };
}

/** Normalize a pg query result into the integer id the rest of the app
 *  expects from `info.lastInsertRowid`. */
function normalizeId(result: QueryResult): number {
  const first = result.rows[0];
  if (first && typeof (first as { id?: unknown }).id === "number") {
    return (first as { id: number }).id;
  }
  if (first && typeof (first as { id?: unknown }).id === "string") {
    return parseInt((first as { id: string }).id, 10);
  }
  return 0;
}

// ---------------------------------------------------------------------------
// Transaction helper — mirrors the old db.transaction(() => {...})() API.
// ---------------------------------------------------------------------------

export interface TransactionClient {
  prepare(sql: string): PreparedQuery;
  query(sql: string, params?: unknown[]): Promise<QueryResult>;
  release(): void;
}

export async function transaction<T>(
  fn: (client: TransactionClient) => T | Promise<T>,
): Promise<T> {
  const client = await getPool().connect();
  const txClient: TransactionClient = {
    prepare: (sql: string) => prepare(sql, client),
    query: (sql: string, params?: unknown[]) => (client as unknown as { query: (text: string, values?: unknown[]) => Promise<QueryResult> }).query(sql, params),
    release: client.release.bind(client),
  };
  try {
    return await fn(txClient);
  } finally {
    client.release();
  }
}

// ---------------------------------------------------------------------------
// Settings helpers (unchanged semantics)
// ---------------------------------------------------------------------------

export function getSetting(key: string): Promise<string | null> {
  return db()
    .prepare("SELECT value FROM settings WHERE key = $1")
    .get(key)
    .then(
      (row: unknown) => {
        const r = row as { value: string } | null;
        return r ? String(r.value) : null;
      },
    );
}

export function setSetting(key: string, value: string): Promise<void> {
  return db()
    .prepare(
      `INSERT INTO settings (key, value) VALUES ($1, $2)
       ON CONFLICT (key) DO UPDATE SET value = excluded.value`,
    )
    .run(key, value)
    .then(() => {});
}

// ---------------------------------------------------------------------------
// JSON helpers (unchanged semantics)
// ---------------------------------------------------------------------------

export function parseJson<T>(value: string | null | undefined, fallback: T): T {
  if (!value) return fallback;
  try {
    return JSON.parse(value) as T;
  } catch {
    return fallback;
  }
}

